import re
import sys
from pathlib import Path

# Path default ke folder backend .NET
DEFAULT_TARGET_DIR = Path(r"E:\Github\aumo-finance\backend\asp-net-core")

# Regex untuk mendeteksi deklarasi tipe/member public
PUBLIC_DECL_REGEX = re.compile(
    r'^(?P<indent>\s*)public\s+(?:static\s+|async\s+|override\s+|virtual\s+|abstract\s+|readonly\s+|sealed\s+)*(?P<type>class|interface|enum|struct|record|[\w<>,\[\]\?\.\=\s]+)\s+(?P<name>\w+)\b'
)

def generate_summary(name: str) -> str:
    """Menghasilkan teks dokumentasi ringkas sesuai konvensi nama C#."""
    words = re.findall(r'[A-Z]?[a-z0-9]+|[A-Z]+(?=[A-Z][a-z0-9]|\b)', name)
    phrase = " ".join(words) if words else name

    if name.endswith("Controller"):
        return f"Controller API untuk mengelola {phrase.replace('Controller', '').strip()}."
    elif name.endswith("Service") or (name.startswith("I") and name.endswith("Service")):
        return f"Layanan logika bisnis untuk {phrase}."
    elif name.endswith("Validator"):
        return f"Validator FluentValidation untuk {phrase}."
    elif name.endswith("Dto") or name.endswith("Request") or name.endswith("Response") or name.endswith("ViewModel"):
        return f"Model data {phrase}."
    elif "DbContext" in name:
        return f"Konteks database Entity Framework {phrase}."
    elif name.startswith("Get"):
        return f"Mengambil data {phrase[3:]}."
    elif name.startswith("Create") or name.startswith("Add"):
        return f"Membuat data {phrase[6:] if name.startswith('Create') else phrase[3:]} baru."
    elif name.startswith("Update") or name.startswith("Edit"):
        return f"Memperbarui data {phrase[6:] if name.startswith('Update') else phrase[4:]}."
    elif name.startswith("Delete") or name.startswith("Remove"):
        return f"Menghapus data {phrase[6:] if name.startswith('Delete') else phrase[6:]}."
    else:
        return f"Mewakili {phrase}."

def process_cs_file(file_path: Path):
    """Menyandarkan dan memperbarui dokumentasi XML pada satu file C#."""
    try:
        content = file_path.read_text(encoding="utf-8")
    except Exception as e:
        print(f"Gagal membaca {file_path.name}: {e}")
        return

    lines = content.splitlines()

    # 1. Hapus XML comment (///) lama untuk menyegarkan struktur
    clean_lines = [line for line in lines if not line.strip().startswith("///")]

    # 2. Sisipkan XML comment secara akurat tepat di atas atribut/deklarasi public
    final_lines = []
    i = 0
    while i < len(clean_lines):
        line = clean_lines[i]
        stripped = line.strip()

        if stripped.startswith("public ") and not stripped.startswith("public class Migration") and "namespace" not in stripped:
            match = PUBLIC_DECL_REGEX.match(line)
            if match:
                name = match.group("name")
                indent = match.group("indent")

                if name not in ["get", "set", "init", "value", "where"]:
                    # Cari puncak paling atas dari blok atribut [...]
                    insert_pos = len(final_lines)
                    while insert_pos > 0:
                        prev_stripped = final_lines[insert_pos - 1].strip()
                        if prev_stripped.startswith("[") or prev_stripped.endswith("]"):
                            insert_pos -= 1
                        else:
                            break

                    summary = generate_summary(name)
                    xml_doc = f"{indent}/// <summary>\n{indent}/// {summary}\n{indent}/// </summary>"
                    final_lines.insert(insert_pos, xml_doc)

        final_lines.append(line)
        i += 1

    new_content = "\n".join(final_lines)
    if new_content != content:
        file_path.write_text(new_content, encoding="utf-8")
        print(f"Diperbarui: {file_path.name}")

def run_fix(target_directory: Path):
    """Menjalankan proses pembersihan pada seluruh file .cs di direktori target."""
    print(f"Mulai memproses proyek di: {target_directory}\n")
    processed_count = 0

    for cs_file in target_directory.rglob("*.cs"):
        # Abaikan folder autogenerated / build
        if "bin" in cs_file.parts or "obj" in cs_file.parts or "Migrations" in cs_file.parts:
            continue
        process_cs_file(cs_file)
        processed_count += 1

    print(f"\nSelesai! {processed_count} file .cs telah diperiksa dan disesuaikan.")

if __name__ == "__main__":
    # Bisa menerima argumen direktori kustom saat dijalankan lewat CLI
    target_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_TARGET_DIR
    if target_dir.exists():
        run_fix(target_dir)
    else:
        print(f"Direktori tidak ditemukan: {target_dir}")