-- Jalankan manual lewat Neon SQL Editor (SEBELUM deploy kode Fase 2 dst.).
-- Tujuan: "GeneralJournal" menjadi TABEL FISIK (bukan view) yang menjadi
-- satu-satunya sumber data jurnal, menggantikan "JournalEntries" dan
-- "JournalEntryLines".
--
-- Alasan tabel fisik: pada fase akhir kedua tabel lama dihapus, sehingga
-- view yang bergantung pada keduanya tidak dapat dipertahankan.
--
-- Desain:
--   * 1 baris = 1 baris jurnal (header didenormalisasi ke setiap baris).
--   * "LineId"         = "JournalEntryLines"."Id" lama (id baris dipertahankan,
--                        karena dipakai DTO dan tabel General Ledger).
--   * "JournalEntryId" = "JournalEntries"."Id" lama (id kelompok/header).
--                        Tidak ada FK karena tabel header akan dihapus.
--                        Id baru dibangkitkan dari sequence
--                        "GeneralJournal_JournalEntryId_seq".
--
-- Skrip ini aman dijalankan berulang (idempotent):
--   a) jika "GeneralJournal" saat ini berupa VIEW / MATERIALIZED VIEW,
--      view tersebut di-drop lalu dibuat ulang sebagai tabel;
--   b) jika tabel sudah ada, hanya constraint/index yang hilang ditambahkan;
--   c) backfill hanya memasukkan baris yang belum ada (berdasarkan "LineId").
-- Data lama di "JournalEntries" dan "JournalEntryLines" TIDAK diubah.

BEGIN;

-- 1) Bentuk "GeneralJournal" saat ini (informasi).
DO $$
DECLARE
    kind "char";
BEGIN
    SELECT c.relkind INTO kind
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE c.relname = 'GeneralJournal' AND n.nspname = current_schema();

    IF kind IS NULL THEN
        RAISE NOTICE 'GeneralJournal belum ada -> akan dibuat sebagai tabel.';
    ELSIF kind = 'v' THEN
        RAISE NOTICE 'GeneralJournal saat ini VIEW -> di-drop, dibuat ulang sebagai tabel.';
        DROP VIEW "GeneralJournal";
    ELSIF kind = 'm' THEN
        RAISE NOTICE 'GeneralJournal saat ini MATERIALIZED VIEW -> di-drop, dibuat ulang sebagai tabel.';
        DROP MATERIALIZED VIEW "GeneralJournal";
    ELSIF kind = 'r' THEN
        RAISE NOTICE 'GeneralJournal sudah berupa tabel -> dipertahankan.';
    END IF;
END $$;

-- 2) Sequence id kelompok jurnal.
CREATE SEQUENCE IF NOT EXISTS "GeneralJournal_JournalEntryId_seq" AS integer;

-- 3) Tabel.
CREATE TABLE IF NOT EXISTS "GeneralJournal" (
    "LineId"          integer GENERATED BY DEFAULT AS IDENTITY,
    "AccountId"       integer NOT NULL,
    "LineDescription" character varying(250) NULL,
    "Debit"           numeric(18,2) NOT NULL DEFAULT 0,
    "Credit"          numeric(18,2) NOT NULL DEFAULT 0,
    "LineOrder"       integer NOT NULL DEFAULT 0,
    "JournalEntryId"  integer NOT NULL,
    "JournalType"     character varying(50) NOT NULL,
    "EntryDate"       timestamp with time zone NOT NULL,
    "TransactionNumber" character varying(30) NOT NULL,
    "UserId"          uuid NOT NULL,
    "Status"          text NULL,
    "CreatedAt"       timestamp with time zone NOT NULL,
    "UpdatedAt"       timestamp with time zone NULL,
    CONSTRAINT "PK_GeneralJournal" PRIMARY KEY ("LineId")
);

-- 4) Foreign key ke ChartOfAccounts (RESTRICT, sejalan dengan pengecekan
--    "akun sudah dipakai jurnal" sebelum akun dihapus).
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'FK_GeneralJournal_ChartOfAccounts_AccountId'
    ) THEN
        ALTER TABLE "GeneralJournal"
            ADD CONSTRAINT "FK_GeneralJournal_ChartOfAccounts_AccountId"
            FOREIGN KEY ("AccountId") REFERENCES "ChartOfAccounts" ("Id")
            ON DELETE RESTRICT;
    END IF;
END $$;

-- 5) Index.
CREATE INDEX IF NOT EXISTS "IX_GeneralJournal_UserId_EntryDate"
    ON "GeneralJournal" ("UserId", "EntryDate");
CREATE INDEX IF NOT EXISTS "IX_GeneralJournal_UserId_TransactionNumber"
    ON "GeneralJournal" ("UserId", "TransactionNumber");
CREATE INDEX IF NOT EXISTS "IX_GeneralJournal_JournalEntryId"
    ON "GeneralJournal" ("JournalEntryId");
CREATE INDEX IF NOT EXISTS "IX_GeneralJournal_AccountId"
    ON "GeneralJournal" ("AccountId");

-- 6) Backfill dari tabel lama (hanya baris yang belum ada).
--    Kolom "Status" pada "JournalEntries" dibaca jika ada; jika tidak,
--    diisi 'Posted'.
DO $$
DECLARE
    status_expr text;
BEGIN
    IF to_regclass('"JournalEntries"') IS NULL
       OR to_regclass('"JournalEntryLines"') IS NULL THEN
        RAISE NOTICE 'Tabel lama tidak ditemukan -> backfill dilewati.';
        RETURN;
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'JournalEntries'
          AND column_name = 'Status'
    ) THEN
        status_expr := 'e."Status"';
    ELSE
        status_expr := '''Posted''';
    END IF;

    EXECUTE format($sql$
        INSERT INTO "GeneralJournal"
            ("LineId", "AccountId", "LineDescription", "Debit", "Credit",
             "LineOrder", "JournalEntryId", "JournalType", "EntryDate",
             "TransactionNumber", "UserId", "Status", "CreatedAt", "UpdatedAt")
        OVERRIDING SYSTEM VALUE
        SELECT l."Id", l."AccountId", l."LineDescription", l."Debit", l."Credit",
               l."LineOrder", e."Id", e."JournalType", e."EntryDate",
               e."TransactionNumber", e."UserId", %s, e."CreatedAt", e."UpdatedAt"
        FROM "JournalEntryLines" l
        JOIN "JournalEntries" e ON e."Id" = l."JournalEntryId"
        WHERE NOT EXISTS (
            SELECT 1 FROM "GeneralJournal" g WHERE g."LineId" = l."Id"
        )
    $sql$, status_expr);
END $$;

-- 7) Selaraskan identity "LineId" dan sequence "JournalEntryId"
--    dengan data yang ada agar id baru tidak bentrok.
SELECT setval(
    pg_get_serial_sequence('"GeneralJournal"', 'LineId'),
    GREATEST(COALESCE((SELECT MAX("LineId") FROM "GeneralJournal"), 0), 1),
    (SELECT COUNT(*) > 0 FROM "GeneralJournal")
);

SELECT setval(
    '"GeneralJournal_JournalEntryId_seq"',
    GREATEST(
        COALESCE((SELECT MAX("JournalEntryId") FROM "GeneralJournal"), 0),
        CASE WHEN to_regclass('"JournalEntries"') IS NULL THEN 0
             ELSE COALESCE((SELECT MAX("Id") FROM "JournalEntries"), 0) END,
        1),
    (SELECT COUNT(*) > 0 FROM "GeneralJournal")
);

COMMIT;

